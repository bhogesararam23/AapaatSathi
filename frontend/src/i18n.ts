void i18n.use(initReactI18next).init({
  resources: {
    en: { translation: en },
    hi: { translation: hi },
    gar: { translation: gar },
  },
  lng: localStorage.getItem("aapaatsathi.lang") || "en",
  fallbackLng: "en",
  interpolation: { escapeValue: false },
  returnNull: false,
});

i18n.on("languageChanged", (lng) => {
  localStorage.setItem("aapaatsathi.lang", lng);
  document.documentElement.lang = lng;
});
document.documentElement.lang = i18n.language;

